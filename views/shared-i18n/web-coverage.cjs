if (process.argv.includes("--check")) {
  if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== report) {
    throw new Error("Web coverage inventory is stale. Run: node views/shared-i18n/web-coverage.cjs --write");
  }
  console.log(`web coverage inventory is current (${routeRows.length} route modules, ${componentRows.length} shared components)`);
} else {
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, report);
  console.log(`generated ${path.relative(viewsRoot, output)} (${routeRows.length} route modules, ${componentRows.length} shared components)`);
}