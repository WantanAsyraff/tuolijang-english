#!/usr/bin/env node
const fs = require("node:fs");
const path = require("node:path");

const viewsRoot = path.resolve(__dirname, "..");
const webRoot = path.join(viewsRoot, "gyro-craftsman-web-own-v2.4");
const sourceRoot = path.join(webRoot, "src");
const viewsDirectory = path.join(sourceRoot, "views");
const routerDirectory = path.join(sourceRoot, "router");
const output = path.join(__dirname, "reports", "web-coverage.md");

function walk(directory, entries = [], { excludeComponentDirectories = false } = {}) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      if (!excludeComponentDirectories || entry.name !== "components") {
        walk(filename, entries, { excludeComponentDirectories });
      }
    } else if (entry.name.endsWith(".vue")) {
      entries.push(filename);
    }
  }
  return entries;
}

function stablePath(filename) {
  return path.relative(viewsDirectory, filename).replaceAll("\\", "/").replace(/\.vue$/, "");
}

function sourceImports(source) {
  const imports = new Set();
  for (const match of source.matchAll(/(?:from\s*|import\s*\()(['"])([^'"]+)\1/g)) {
    if (match[2].includes("components") || match[2].startsWith("./") || match[2].startsWith("../")) imports.add(match[2]);
  }
  return [...imports].sort();
}

const routerSource = fs.readdirSync(routerDirectory, { withFileTypes: true }).filter((entry) => entry.isFile() && entry.name.endsWith(".js")).map((entry) => fs.readFileSync(path.join(routerDirectory, entry.name), "utf8")).join("\n");
const staticViews = new Set([...routerSource.matchAll(/@\/views\/([^'"`)]+)/g)].map((match) => match[1].replace(/\.vue$/, "")));
function buildRows(files, { kind, baseDirectory }) {
  return files
    .map((filename) => {
      const source = fs.readFileSync(filename, "utf8");
      const modulePath = path.relative(baseDirectory, filename).replaceAll("\\", "/").replace(/\.vue$/, "");
      const isStatic = kind === "route" && staticViews.has(modulePath);
      const route = kind === "route"
        ? (isStatic ? `static: ${modulePath}` : `dynamic menu candidate: ${modulePath}`)
        : `shared component: ${modulePath}`;
      const components = sourceImports(source);
      return {
        route,
        file: `views/gyro-craftsman-web-own-v2.4/src/${kind === "route" ? "views" : "components"}/${modulePath}.vue`,
        components: components.length ? components.join(", ") : "—",
        staticAudit: "PASS — canonical i18n:audit --app web",
        runtimeAudit: "BLOCKED — authenticated browser session, permission menu, and representative API data are required",
        status: "BLOCKED",
        notes: kind === "component"
          ? "Shared component. It is statically covered and must be observed through every route/dialog/drawer that mounts it before runtime PASS."
          : isStatic
            ? "Registered static route; runtime evidence is required before it can be marked PASS."
            : "Potentially registered through backend permission menus; source is included by router require.context and needs a matching entitled account for runtime verification.",
      };
    })
    .sort((left, right) => left.file.localeCompare(right.file));
}

const routeRows = buildRows(walk(viewsDirectory, [], { excludeComponentDirectories: true }), {
  kind: "route",
  baseDirectory: viewsDirectory,
});
const componentDirectory = path.join(sourceRoot, "components");
const componentRows = buildRows(walk(componentDirectory), {
  kind: "component",
  baseDirectory: componentDirectory,
});

function cell(value) {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}

