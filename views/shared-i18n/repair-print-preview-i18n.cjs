function readCatalog(file) {
  const source = fs.readFileSync(file, "utf8");
  const match = source.match(/export default\s+(\{[\s\S]*\})\s*;?\s*$/);
  if (!match) throw new Error(`Unable to parse ${file}`);
  return JSON.parse(match[1]);
}

function writeCatalog(file, catalog) {
  const sorted = Object.fromEntries(Object.entries(catalog).sort(([left], [right]) => left.localeCompare(right)));
  fs.writeFileSync(
    file,
    `// Generated by migrate-vue-ui-i18n.cjs. Do not edit by hand.\nexport default ${JSON.stringify(sorted, null, 2)};\n`
  );
}

