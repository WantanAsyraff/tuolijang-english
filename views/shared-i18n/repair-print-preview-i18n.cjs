function rootTemplateBlock(source) {
  const start = source.indexOf("<template");
  const boundaryCandidates = [
    source.indexOf("<script", start + 9),
    source.indexOf("<style", start + 9),
  ].filter((value) => value >= 0);
  const boundary = boundaryCandidates.length ? Math.min(...boundaryCandidates) : source.length;
  const end = source.lastIndexOf("</template>", boundary);
  if (start < 0 || end < start) throw new Error("Unable to resolve root template");
  return { start, end: boundary, value: source.slice(start, end + "</template>".length) };
}

