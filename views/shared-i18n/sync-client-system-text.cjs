const fs = require('fs')
const path = require('path')
const { pathToFileURL } = require('url')

const root = path.resolve(__dirname, '..')

function moduleSource(map, typed) {
  const sharedSource = fs.readFileSync(path.join(__dirname, 'index.js'), 'utf8')
  const runtimeStart = sharedSource.indexOf('const HAS_HAN =')
  if (runtimeStart < 0) throw new Error('Shared localization runtime was not found')
  const runtime = sharedSource
    .slice(runtimeStart)
    .replace(/normalizeLocale/g, 'normalizeSystemLocale')
  const typeGuard = typed ? '// @ts-nocheck\n' : ''
  return `${typeGuard}// Generated by ../shared-i18n/sync-client-system-text.cjs. Do not edit by hand.\nexport const SYSTEM_TEXT_EN = Object.freeze(${JSON.stringify(map, null, 2)})\n\n${runtime}`
}
async function main() {
  const shared = await import(pathToFileURL(path.join(__dirname, 'index.js')).href)
  const targets = [
    ['gyro-craftsman-web-own-v2.4/src/lang/system-text.js', false],
    ['gyro-craftsman-chat-v1.0/src/locale/system-text.ts', true],
    ['view-uni-src/locale/system-text.ts', true]
  ]
  for (const [relative, typed] of targets) {
    fs.writeFileSync(path.join(root, relative), moduleSource(shared.SYSTEM_TEXT_EN, typed))
  }

  const imports = [
    ['gyro-craftsman-web-own-v2.4/src/utils/i18ns.js', "../../../shared-i18n/index.js", "@/lang/system-text"],
    ['gyro-craftsman-chat-v1.0/src/locale/index.ts', "../../../shared-i18n/index.js", "./system-text"],
    ['view-uni-src/locale/index.ts', "../../shared-i18n/index.js", "./system-text"]
  ]
  for (const [relative, from, to] of imports) {
    const file = path.join(root, relative)
    const source = fs.readFileSync(file, 'utf8').replace(from, to)
    fs.writeFileSync(file, source)
  }
  console.log(`Synchronized ${Object.keys(shared.SYSTEM_TEXT_EN).length} system-text mappings into all clients.`)
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
