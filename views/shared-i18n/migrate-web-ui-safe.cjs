const fs = require("fs");
const path = require("path");
const { pathToFileURL } = require("url");
const babelParser = require("../gyro-craftsman-web-own-v2.4/node_modules/@babel/parser");
const MANUAL_EN = { ...require("./manual-ui-en.cjs"), ...require("./manual-ui-en-extra.cjs") };

const root = path.resolve(__dirname, "../gyro-craftsman-web-own-v2.4");
const sourceRoot = path.join(root, "src");
const enFile = path.join(root, "src/lang/generated-ui-en.js");
const zhFile = path.join(root, "src/lang/generated-ui-zh.js");
const HAS_HAN = /[\u3400-\u9fff]/;
const VISIBLE_ATTRIBUTES = [
  "alt",
  "aria-label",
  "button-text",
  "button-title",
  "cancel-button-text",
  "cancel-text",
  "confirm-button-text",
  "confirm-text",
  "content",
  "default-title",
  "description",
  "empty-text",
  "label",
  "loading-text",
  "placeholder",
  "popup-title",
  "right-text",
  "text",
  "tip",
  "tips",
  "title",
  "unit",
].sort((a, b) => b.length - a.length);

function files(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) return entry.name === "node_modules" ? [] : files(full);
    return entry.name.endsWith(".vue") ? [full] : [];
  });
}

function readGenerated(file) {
  if (!fs.existsSync(file)) return {};
  const match = fs.readFileSync(file, "utf8").match(/export default\s+(\{[\s\S]*\})\s*;?\s*$/);
  if (!match) throw new Error(`Unable to parse ${file}`);
  return JSON.parse(match[1]);
}

function generatedSource(catalog) {
  const sorted = Object.fromEntries(Object.entries(catalog).sort(([a], [b]) => a.localeCompare(b)));
  return `// Generated by migrate-web-ui-safe.cjs. Do not edit by hand.\nexport default ${JSON.stringify(sorted, null, 2)};\n`;
}

function clean(value) {
  return String(value || "").replace(/\s+/g, " ").trim();
}

function words(value) {
  return String(value || "")
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/[^A-Za-z0-9]+/g, " ")
    .trim()
    .split(/\s+/)
    .filter(Boolean);
}

function camel(value) {
  return words(value)
    .map((part, index) => {
      const lower = part.toLowerCase();
      return index ? lower.charAt(0).toUpperCase() + lower.slice(1) : lower;
    })
    .join("");
}

function commentRanges(template) {
  return [...template.matchAll(/<!--[\s\S]*?-->/g)].map((match) => ({
    start: match.index,
    end: match.index + match[0].length,
  }));
}

function inside(ranges, offset) {
  return ranges.some((range) => offset >= range.start && offset < range.end);
}

function parseExpression(source) {
  return babelParser.parseExpression(source, {
    sourceType: "module",
    plugins: ["typescript", "optionalChaining", "nullishCoalescingOperator"],
  });
}

function walkExpression(node, parent, register, replacements) {
  if (!node || typeof node !== "object") return;
  const comparison =
    parent &&
    ((parent.type === "BinaryExpression" && ["==", "===", "!=", "!==", "in"].includes(parent.operator)) ||
      parent.type === "SwitchCase");
  const translated =
    parent &&
    parent.type === "CallExpression" &&
    ["$t", "$ts", "t", "translate", "translateSystemText"].includes(
      parent.callee?.name || parent.callee?.property?.name
    );
  const key = parent && parent.type === "ObjectProperty" && parent.key === node && !parent.computed;
  if (!comparison && !translated && !key && node.type === "StringLiteral" && HAS_HAN.test(node.value)) {
    replacements.push({
      start: node.start,
      end: node.end,
      value: `$t('${register(node.value)}')`,
    });
    return;
  }
  if (
    !comparison &&
    !translated &&
    node.type === "TemplateLiteral" &&
    !node.expressions.length &&
    HAS_HAN.test(node.quasis[0]?.value?.cooked || "")
  ) {
    replacements.push({
      start: node.start,
      end: node.end,
      value: `$t('${register(node.quasis[0].value.cooked)}')`,
    });
    return;
  }
  for (const [field, value] of Object.entries(node)) {
    if (["loc", "start", "end", "leadingComments", "trailingComments", "innerComments"].includes(field)) continue;
    if (Array.isArray(value)) value.forEach((child) => walkExpression(child, node, register, replacements));
    else if (value && typeof value === "object") walkExpression(value, node, register, replacements);
  }
}

function transformExpression(source, register) {
  if (!HAS_HAN.test(source)) return source;
  let ast;
  try {
    ast = parseExpression(source);
  } catch {
    return source;
  }
  const replacements = [];
  walkExpression(ast, null, register, replacements);
  return replacements
    .sort((a, b) => b.start - a.start)
    .reduce((result, item) => result.slice(0, item.start) + item.value + result.slice(item.end), source);
}

function translateText(raw, register) {
  const edge = "(?:\\s|&nbsp;|&emsp;|&#160;)*";
  const match = raw.match(new RegExp(`^(${edge})([\\s\\S]*?)(${edge})$`));
  const leading = match?.[1] || "";
  const value = match?.[2] || raw;
  const trailing = match?.[3] || "";
  if (!HAS_HAN.test(value)) return raw;
  return `${leading}{{ $t('${register(value)}') }}${trailing}`;
}

function transformTextContent(content, register) {
  if (!HAS_HAN.test(content)) return content;
  const output = [];
  let cursor = 0;
  for (const match of content.matchAll(/\{\{([\s\S]*?)\}\}/g)) {
    const staticPart = content.slice(cursor, match.index);
    output.push(translateText(staticPart, register));
    const expression = match[1];
    output.push(`{{${transformExpression(expression, register)}}}`);
    cursor = match.index + match[0].length;
  }
  output.push(translateText(content.slice(cursor), register));
  return output.join("");
}

function transformTemplate(template, register) {
  const ranges = commentRanges(template);
  const replacements = [];
  for (const match of template.matchAll(/>([^<]*)</g)) {
    if (inside(ranges, match.index)) continue;
    const content = match[1];
    const next = transformTextContent(content, register);
    if (next !== content) {
      const start = match.index + 1;
      replacements.push({ start, end: start + content.length, value: next });
    }
  }

  const names = VISIBLE_ATTRIBUTES.map((name) => name.replace("-", "\\-")).join("|");
  const attrPattern = new RegExp(
    `(\\s)((?::|v-bind:)?)(?:${names})\\s*=\\s*(\"([^\"]*)\"|'([^']*)')`,
    "gi"
  );
  for (const match of template.matchAll(attrPattern)) {
    if (inside(ranges, match.index)) continue;
    const full = match[0];
    const prefix = match[2];
    const quote = match[3][0];
    const value = match[4] ?? match[5] ?? "";
    if (!HAS_HAN.test(value)) continue;
    const nameMatch = full.match(/(?:^|\s)(?::|v-bind:)?((?:alt|aria-label|button-text|button-title|cancel-button-text|cancel-text|confirm-button-text|confirm-text|content|default-title|description|empty-text|label|loading-text|placeholder|popup-title|right-text|text|tip|tips|title|unit))\s*=/i);
    if (!nameMatch) continue;
    const name = nameMatch[1];
    const nextValue = prefix ? transformExpression(value, register) : `$t('${register(value)}')`;
    if (nextValue === value) continue;
    const replacement = `${match[1]}:${name}=${quote}${nextValue}${quote}`;
    replacements.push({
      start: match.index,
      end: match.index + full.length,
      value: replacement,
    });
  }

  const filtered = replacements
    .sort((a, b) => a.start - b.start)
    .filter((item, index, items) => index === 0 || item.start >= items[index - 1].end);
  return filtered
    .sort((a, b) => b.start - a.start)
    .reduce((result, item) => result.slice(0, item.start) + item.value + result.slice(item.end), template);
}

async function run() {
  const shared = await import(pathToFileURL(path.join(__dirname, "index.js")).href);
  const en = readGenerated(enFile);
  const zh = readGenerated(zhFile);
  const used = new Set([...Object.keys(en), ...Object.keys(zh)]);
  const pairs = new Map();
  Object.keys(zh).forEach((key) => pairs.set(`${zh[key]}\u0000${en[key] || ""}`, key));
  const unresolved = new Map();
  const pending = new Map();
  let relative = "";

  function register(raw) {
    const zhValue = clean(raw);
    const enValue = clean(MANUAL_EN[zhValue] || shared.translateSystemTextValue(zhValue, { locale: "en" }));
    if (!enValue || HAS_HAN.test(enValue)) {
      if (!unresolved.has(zhValue)) unresolved.set(zhValue, relative);
      return "ui.missingTranslation";
    }
    const pair = `${zhValue}\u0000${enValue}`;
    if (pairs.has(pair)) return `ui.${pairs.get(pair)}`;
    const stem = relative
      .replace(/\\/g, "/")
      .replace(/\.vue$/i, "")
      .split("/")
      .filter((part) => !["src", "views", "components"].includes(part))
      .slice(-5)
      .join(" ");
    let key = camel(`${stem} ${words(enValue).slice(0, 9).join(" ")}`).slice(0, 120) || "text";
    const base = key;
    let suffix = 2;
    while (used.has(key)) key = `${base}${suffix++}`;
    used.add(key);
    pairs.set(pair, key);
    en[key] = enValue;
    zh[key] = zhValue;
    return `ui.${key}`;
  }

  for (const file of files(sourceRoot)) {
    const source = fs.readFileSync(file, "utf8");
    const match = source.match(/<template(?:\s[^>]*)?>([\s\S]*?)<\/template>/i);
    if (!match || match.index == null) continue;
    relative = path.relative(sourceRoot, file);
    const template = match[1];
    const nextTemplate = transformTemplate(template, register);
    if (nextTemplate === template) continue;
    const start = match.index + match[0].indexOf(template);
    pending.set(file, source.slice(0, start) + nextTemplate + source.slice(start + template.length));
  }

  if (unresolved.size) {
    throw new Error(
      `Missing ${unresolved.size} English translations:\n` +
        [...unresolved].map(([text, file]) => `${file}: ${text}`).join("\n")
    );
  }
  pending.forEach((source, file) => fs.writeFileSync(file, source, "utf8"));
  fs.writeFileSync(enFile, generatedSource(en), "utf8");
  fs.writeFileSync(zhFile, generatedSource(zh), "utf8");
  console.log(`Safely migrated ${pending.size} web templates with ${Object.keys(en).length} explicit UI keys.`);
}

run().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
