function resolveI18nContext(ctx) {
  if (!ctx) return null
  if (ctx.$te && ctx.$t) return ctx
  if (ctx.te && ctx.t) return { $te: ctx.te.bind(ctx), $t: ctx.t.bind(ctx) }
  return null
}

function getLocale(ctx) {
  if (ctx && ctx.$i18n && ctx.$i18n.locale) return ctx.$i18n.locale
  if (ctx && ctx.locale) return ctx.locale
  return 'zh-cn'
}

function translateByKey(key, ctx) {
  const locale = getLocale(ctx)
  const i18n = resolveI18nContext(ctx)
  const i18nKey = `systemText.${key}`
  if (i18n && i18n.$te(i18nKey)) return i18n.$t(i18nKey)
  if (systemTextTranslations[locale] && systemTextTranslations[locale][key]) return systemTextTranslations[locale][key]
  if (locale === 'en' && systemTextTranslations.en[key]) return systemTextTranslations.en[key]
  return null
}

function translateDirectText(text, ctx) {
  const locale = getLocale(ctx)
  const normalizedText = String(text || '').trim().replace(/[：:]$/, '')
  if (!normalizedText) return text
  if (directTextTranslations[locale] && directTextTranslations[locale][normalizedText]) {
    return directTextTranslations[locale][normalizedText]
  }
  if (locale === 'en' && directTextTranslations.en[normalizedText]) return directTextTranslations.en[normalizedText]
  const compactText = normalizedText.replace(/\s+/g, '')
  if (compactText !== normalizedText) {
    if (directTextTranslations[locale] && directTextTranslations[locale][compactText]) {
      return directTextTranslations[locale][compactText]
    }
    if (locale === 'en' && directTextTranslations.en[compactText]) return directTextTranslations.en[compactText]
  }
  return text
}

export function translateSystemText(text, ctx, englishValue) {
  if (!text) return text
  const rawText = String(text)
  const sharedTranslation = translateSystemTextValue(rawText, {
    locale: getLocale(ctx),
    englishValue
  })
  if (sharedTranslation !== rawText) return sharedTranslation
  const normalizedText = rawText.trim().replace(/[：:]$/, '')
  const direct = translateDirectText(normalizedText, ctx)
  if (direct !== normalizedText) return direct
  const key = systemTextKeyMap[normalizedText]
  if (!key) return text
  const translated = translateByKey(key, ctx)
  return translated || text
}

export function translateRuntimeText(text, ctx, englishValue) {
  if (!text) return text
  const rawText = String(text)
  const trimmed = rawText.trim()
  if (!trimmed) return text
  const locale = getLocale(ctx)
  const sharedTranslation = translateSystemTextValue(rawText, { locale, englishValue })
  if (sharedTranslation !== rawText) return sharedTranslation
  const withoutColon = trimmed.replace(/[:：]$/, '')
  const translated = translateSystemText(withoutColon, ctx, englishValue)
  if (translated !== withoutColon) {
    const suffix = /[:：]$/.test(trimmed) ? ':' : ''
    return rawText.replace(trimmed, `${translated}${suffix}`)
  }
  if (locale !== 'en') return text

  const directRuntime = translateDirectText(withoutColon, ctx)
  if (directRuntime !== withoutColon) {
    const suffix = /[:：]$/.test(trimmed) ? ':' : ''
    return rawText.replace(trimmed, `${directRuntime}${suffix}`)
  }

  const monthNames = [
    'January',
    'February',
    'March',
    'April',
    'May',
    'June',
    'July',
    'August',
    'September',
    'October',
    'November',
    'December'
  ]

  return rawText
    .replace(/(\d{4})\s*年\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日/g, (_, y, m, d) => {
      return `${monthNames[Number(m) - 1]} ${Number(d)}, ${y}`
    })
    .replace(/(\d{4})\s*年\s*(\d{1,2})\s*月/g, (_, y, m) => `${monthNames[Number(m) - 1]} ${y}`)
    .replace(/(\d{1,2})月(\d{1,2})日/g, (_, m, d) => `${monthNames[Number(m) - 1]} ${Number(d)}`)
    .replace(/还有(\d+)个日程/g, (_, num) => `${num} more schedules`)
    .replace(/共\s*(\d+)\s*条/g, (_, num) => `Total ${num}`)
    .replace(/(\d+)\s*条\/页/g, (_, num) => `${num} / page`)
    .replace(/前往\s*(\d+)\s*页/g, (_, num) => `Go to page ${num}`)
    .replace(/（主）|\(主\)/g, '(Primary)')
    .replace(/（管）|\(管\)/g, '(Manager)')
    .replace(/([^\s]+)岗位职责/g, '$1 job duties')
    .replace(/填写情况/g, 'submission status')
    .replace(/统计时间[:：]/g, 'Statistics time:')
    .replace(/制表时间[:：]/g, 'Report generated time:')
    .replace(/(\d+(?:\.\d+)?)小时/g, '$1 hours')
    .replace(/(\d+(?:\.\d+)?)分钟/g, '$1 minutes')
    .replace(/(\d{4})\s*年(?!\s*\d)/g, '$1')
    .replace(/(\d+)天/g, '$1 days')
    .replace(/第一季度/g, 'Q1')
    .replace(/第二季度/g, 'Q2')
    .replace(/第三季度/g, 'Q3')
    .replace(/第四季度/g, 'Q4')
    .replace(/(\d{1,2})月/g, (_, m) => monthNames[Number(m) - 1] || `${m}`)
}

const CHART_FORMATTER_KEYS = new Set(['formatter', 'labelFormatter', 'valueFormatter'])

function localizeChartValue(value, ctx, seen, key = '') {
  if (typeof value === 'string') return translateRuntimeText(value, ctx)
  if (typeof value === 'function' && CHART_FORMATTER_KEYS.has(key)) {
    const original = value.__chartI18nOriginal || value
    const wrapped = function localizedChartFormatter(...args) {
      return localizeChartValue(original.apply(this, args), ctx, new WeakMap())
    }
    Object.defineProperty(wrapped, '__chartI18nOriginal', { value: original })
    return wrapped
  }
  if (!value || typeof value !== 'object') return value
  if (value instanceof Date || value instanceof RegExp) return value
  if (seen.has(value)) return seen.get(value)

  const localized = Array.isArray(value) ? [] : {}
  seen.set(value, localized)
  Object.keys(value).forEach((childKey) => {
    localized[childKey] = localizeChartValue(value[childKey], ctx, seen, childKey)
  })
  return localized
}

export function localizeChartOption(option, ctx) {
  return localizeChartValue(option || {}, ctx, new WeakMap())
}
