function flattenLocaleMessages(zhNode, enNode, target = {}) {
  if (!zhNode || !enNode || typeof zhNode !== 'object' || typeof enNode !== 'object') return target
  Object.keys(zhNode).forEach((key) => {
    const zhValue = zhNode[key]
    const enValue = enNode[key]
    if (typeof zhValue === 'string' && typeof enValue === 'string') {
      const normalized = zhValue.trim().replace(/[：:]$/, '')
      if (normalized && /[\u4e00-\u9fff]/.test(normalized)) target[normalized] = enValue.trim().replace(/[：:]$/, '')
      return
    }
    if (zhValue && enValue && typeof zhValue === 'object' && typeof enValue === 'object') {
      flattenLocaleMessages(zhValue, enValue, target)
    }
  })
  return target
}

